"""Design-sheet tooling: `preflight` lays every sheet over the others and lists unfilled cells and
unresolved references; `gen` writes launcher/gen_sheets.go from the sheets (one struct per row)."""
import json, sys, glob, os, fnmatch, re, struct
sys.path.insert(0, os.path.dirname(__file__))
import wad

H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # the source folder
S = {n: json.load(open(f"{H}/sheets/{n}.json")) for n in ["asset_classes", "grades", "render", "hooks", "upscalers"]}
ORIG = os.environ.get("SACRIFICE_DATA", f"{H}/orig")  # your Sacrifice\\data folder (preflight only)

def rows(n): return S[n]["rows"]

def preflight(strict_verified=False):
    probs, unverified = [], []
    for n, sh in S.items():
        cols = sh["columns"]
        for r in sh["rows"]:
            for c in cols:
                if c not in r or r[c] is None or (isinstance(r[c], str) and r[c].strip() == "" and c not in ("section",)):
                    if n == "upscalers" and c in ("exe", "args", "fallback") and r["id"] == "lanczos": continue
                    if n == "render" and c == "section" and r["target"] != "dgVoodoo.conf": continue
                    probs.append(f"{n}.{r.get('id')}.{c}: unfilled")
            extra = set(r) - set(cols)
            if extra: probs.append(f"{n}.{r.get('id')}: cells outside columns {extra}")
            if r.get("verified") != "yes": unverified.append(f"{n}.{r['id']}")
    grades = {g["id"] for g in rows("grades")}
    scales = {u["scale"] for u in rows("upscalers") if u["scale"]}
    wads = {os.path.relpath(p, ORIG).replace("\\", "/") for p in glob.glob(f"{ORIG}/*.wad") + glob.glob(f"{ORIG}/local/*.wad")}
    for a in rows("asset_classes"):
        if a["palette"] not in ("joint_per_palt", "keep_original", "none", "regrade_in_place"): probs.append(f"asset_classes.{a['id']}.palette -> {a['palette']} unknown")
        if a["grade"] not in grades: probs.append(f"asset_classes.{a['id']}.grade -> {a['grade']} not in grades")
        if a["format"] != "palette_land":
            for s in (a["scaleSmall"], a["scaleLarge"]):
                if s != 1 and s not in scales: probs.append(f"asset_classes.{a['id']}: scale {s} has no upscaler row")
        for src in a["sources"] + a["excludes"]:
            w = src.split(":")[0]
            if not any(fnmatch.fnmatch(x, w) for x in wads): probs.append(f"asset_classes.{a['id']}: source {src} matches no wad")
    # coverage: every texture chunk belongs to exactly one class or is excluded
    def owner(wn, path, typ):
        hits = []
        for a in rows("asset_classes"):
            if a["chunkType"] != typ: continue
            def m(spec):
                w, _, pre = spec.partition(":")
                return fnmatch.fnmatch(wn, w) and (not pre or path.startswith(pre))
            if any(m(s) for s in a["excludes"]): return ["excluded"]
            if any(m(s) for s in a["sources"]): hits.append(a["id"])
        return hits
    counts = {}
    for wn in sorted(wads):
        r, _ = wad.read(f"{ORIG}/{wn}", load=False)
        for p, e in r.walk():
            if e.flag & 1 or e.type not in ("TXTR", "ICON", "SXTX"): continue
            o = owner(wn, p, e.type)
            if len(o) != 1: probs.append(f"coverage: {wn}{p} ({e.type}) owned by {o or 'nobody'}")
            else: counts[o[0]] = counts.get(o[0], 0) + 1
    conf = open(f"{H}/third-party/dgVoodoo.template.conf", encoding="latin1").read()
    for rr in rows("render"):
        if rr["target"] == "dgVoodoo.conf" and not re.search(r"^\[%s\][^\[]*^%s\s*=" % (re.escape(rr["section"]), re.escape(rr["key"])), conf, re.M | re.S):
            probs.append(f"render.{rr['id']}: key {rr['section']}.{rr['key']} not in dgVoodoo.conf")
    for u in rows("upscalers"):
        if u["exe"] and not os.path.exists(f"{H}/vendor/resr_win/" + u["exe"].split("/", 1)[1]):
            probs.append(f"upscalers.{u['id']}: exe missing from bundle")
        if u["model"] != "lanczos3" and not os.path.exists(f"{H}/vendor/resr_win/models/{u['model']}-x{u['scale']}.param"):
            probs.append(f"upscalers.{u['id']}: model file missing")
    print("coverage:", counts)
    print(f"PROBLEMS ({len(probs)}):"); [print("  ", p) for p in probs]
    print(f"UNVERIFIED ({len(unverified)}):", ", ".join(unverified))
    return not probs and (not strict_verified or not unverified)

def gen():
    q = json.dumps
    out = ["// Code generated by tools/sheets.py from sheets/*.json. DO NOT EDIT.", "package main", ""]
    out += ["type Grade struct {\n\tID string\n\tSaturation, Contrast, SharpenRadius, SharpenAmount float64\n}", ""]
    out.append("var Grades = map[string]Grade{")
    for g in rows("grades"):
        out.append(f'\t{q(g["id"])}: {{{q(g["id"])}, {g["saturation"]}, {g["contrast"]}, {g["sharpenRadius"]}, {g["sharpenAmount"]}}},')
    out += ["}", ""]
    out += ["type AssetClass struct {\n\tID, Category, ChunkType string\n\tSources, Excludes []string\n\tFormat string\n\tScaleSmall, ScaleLarge, MaxDim int\n\tGrade, Alpha, Palette, FrameHeader string\n}", ""]
    out.append("var AssetClasses = []AssetClass{")
    for a in rows("asset_classes"):
        out.append(f'\t{{{q(a["id"])}, {q(a["category"])}, {q(a["chunkType"])}, []string{{{", ".join(map(q, a["sources"]))}}}, []string{{{", ".join(map(q, a["excludes"]))}}}, {q(a["format"])}, {a["scaleSmall"]}, {a["scaleLarge"]}, {a["maxDim"]}, {q(a["grade"])}, {q(a["alpha"])}, {q(a["palette"])}, {q(a["frameHeader"])}}},')
    out += ["}", ""]
    out += ["type Upscaler struct {\n\tID string\n\tScale int\n\tExe, Model, Args, Fallback string\n}", ""]
    out.append("var Upscalers = []Upscaler{")
    for u in rows("upscalers"):
        out.append(f'\t{{{q(u["id"])}, {u["scale"]}, {q(u["exe"])}, {q(u["model"])}, {q(u["args"])}, {q(u["fallback"])}}},')
    out += ["}", ""]
    out += ["type RenderRow struct {\n\tID, Target, Section, Key, Value string\n}", ""]
    out.append("var RenderRows = []RenderRow{")
    for r in rows("render"):
        out.append(f'\t{{{q(r["id"])}, {q(r["target"])}, {q(r["section"])}, {q(r["key"])}, {q(str(r["value"]))}}},')
    out += ["}", ""]
    open(f"{H}/launcher/gen_sheets.go", "w").write("\n".join(out) + "\n")
    print("wrote gen_sheets.go")

if __name__ == "__main__":
    if sys.argv[1] == "preflight": sys.exit(0 if preflight("--strict" in sys.argv) else 1)
    if sys.argv[1] == "gen": gen()
